"""Planner Agent: converts profiler facts and user intent into a safe ML plan."""

from __future__ import annotations
import importlib.util

from .schemas import AnalysisPlan, DatasetProfile, Objective, ProblemType


class PlannerAgent:
    """A deterministic first implementation of the Data Pilot Planner.

    The agent deliberately consumes facts generated by a profiler. It never reads files,
    runs user supplied code, or computes statistics itself.  An LLM may later propose a
    plan, but the same validation rules should remain at this boundary.
    """

    _CLASSIFICATION_MODELS = (
        "logistic_regression",
        "decision_tree_classifier",
        "random_forest_classifier",
        "gradient_boosting_classifier",
        *( ("xgboost_classifier",) if importlib.util.find_spec("xgboost") else () ),
    )
    _REGRESSION_MODELS = (
        "linear_regression",
        "ridge_regression",
        "decision_tree_regressor",
        "random_forest_regressor",
        "gradient_boosting_regressor",
        *( ("xgboost_regressor",) if importlib.util.find_spec("xgboost") else () ),
    )

    def create_plan(self, profile: DatasetProfile, objective: Objective | None = None) -> AnalysisPlan:
        objective = objective or Objective()
        target, target_warning = self._resolve_target(profile, objective)
        problem_type = self._resolve_problem_type(profile, objective, target)

        warnings = list(profile.warnings)
        assumptions: list[str] = []
        if target_warning:
            warnings.append(target_warning)
        if problem_type == "unknown":
            warnings.append("No ML problem was selected because no trustworthy target column was available.")
            steps = ("profile", "clean", "eda")
            models: tuple[str, ...] = ()
            metric = None
            validation = "not_applicable"
        elif problem_type == "classification":
            steps = ("profile", "clean", "eda", "feature_engineering", "train_models", "evaluate", "explain")
            models = self._CLASSIFICATION_MODELS
            imbalanced = profile.class_imbalance_ratio is not None and profile.class_imbalance_ratio < 0.75
            metric = "f1_weighted" if imbalanced else "roc_auc"
            validation = "stratified_k_fold"
            if imbalanced:
                assumptions.append("Class imbalance was detected; prioritize F1 and minority-class recall.")
        else:
            steps = ("profile", "clean", "eda", "feature_engineering", "train_models", "evaluate", "explain")
            models = self._REGRESSION_MODELS
            metric = "rmse"
            validation = "k_fold"

        if profile.duplicate_rows:
            assumptions.append("Remove duplicate rows during preprocessing.")
        if any(column.missing_count for column in profile.columns):
            assumptions.append("Impute missing feature values inside a training pipeline.")

        goal = objective.text.strip() or self._default_goal(problem_type, target)
        return AnalysisPlan(
            goal=goal,
            target_column=target,
            problem_type=problem_type,
            steps=steps,
            recommended_models=models,
            primary_metric=metric,
            validation_strategy=validation,
            assumptions=tuple(assumptions),
            warnings=tuple(warnings),
        )

    @staticmethod
    def _resolve_target(profile: DatasetProfile, objective: Objective) -> tuple[str | None, str | None]:
        available = {column.name for column in profile.columns}
        if objective.target_column:
            if objective.target_column in available:
                return objective.target_column, None
            return None, f"Requested target column '{objective.target_column}' is not present in the profile."
        if len(profile.potential_target_columns) == 1:
            return profile.potential_target_columns[0], None
        if len(profile.potential_target_columns) > 1:
            return None, "Multiple potential target columns were found; provide target_column explicitly."
        return None, "No target column was identified; provide target_column explicitly."

    @staticmethod
    def _resolve_problem_type(profile: DatasetProfile, objective: Objective, target: str | None) -> ProblemType:
        if objective.problem_type != "unknown":
            return objective.problem_type
        if not target:
            return "unknown"
        column = profile.column(target)
        if column is None:
            return "unknown"
        if column.kind in {"categorical", "boolean"}:
            return "classification"
        if column.kind == "numeric":
            # Binary numeric targets (e.g. 0/1) indicate classification; otherwise continuous numeric defaults to regression
            return "classification" if column.unique_count <= 2 else "regression"
        return "unknown"

    @staticmethod
    def _default_goal(problem_type: ProblemType, target: str | None) -> str:
        if problem_type == "unknown":
            return "Understand and prepare the dataset for analysis"
        verb = "Predict" if problem_type == "classification" else "Estimate"
        return f"{verb} {target}"
