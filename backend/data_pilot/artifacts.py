"""Versioned local model artifact persistence for trusted, internally-created models."""
from __future__ import annotations
import json, os
from pathlib import Path
from uuid import uuid4, UUID
from datetime import datetime, timezone
import joblib
import sklearn

class ArtifactStore:
    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
    def save_model(self, estimator, preprocessor, model_name: str, feature_names: list[str], datetime_columns: list[str] | None = None, target_classes: list | None = None) -> dict:
        artifact_id = str(uuid4())
        folder = self.root / artifact_id
        folder.mkdir(parents=True, exist_ok=False)
        model_path = folder / "model_bundle.joblib"
        joblib.dump({"estimator": estimator, "preprocessor": preprocessor, "model_name": model_name, "feature_names": feature_names, "datetime_columns": datetime_columns or [], "target_classes": target_classes or []}, model_path)
        manifest = {"artifact_id": artifact_id, "model_name": model_name, "file": "model_bundle.joblib", "created_at": datetime.now(timezone.utc).isoformat(), "python_sklearn_version": sklearn.__version__, "warning": "Only load artifacts generated by this trusted Data Pilot instance; joblib/pickle files can execute code when loaded."}
        (folder / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        return {"artifact_id": artifact_id, "artifact_path": str(model_path.relative_to(self.root)), "manifest": manifest}

    def load_model(self, artifact_id: str) -> dict:
        safe_id = str(UUID(artifact_id))
        model_path = (self.root / safe_id / "model_bundle.joblib").resolve()
        if self.root not in model_path.parents or not model_path.is_file():
            raise FileNotFoundError("Model artifact not found")
        return joblib.load(model_path)
