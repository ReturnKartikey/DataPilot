"""Versioned local model artifact persistence for trusted, internally-created models."""
from __future__ import annotations

import hashlib
import hmac
import json
import os
import secrets
from datetime import datetime, timezone
from pathlib import Path
from uuid import UUID, uuid4

import joblib
import sklearn


class ArtifactStore:
    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _signing_key(self) -> bytes:
        configured = os.getenv("DATAPILOT_ARTIFACT_SIGNING_KEY", "").strip()
        if configured:
            return configured.encode("utf-8")
        key_file = self.root / ".artifact_hmac_key"
        if key_file.is_file():
            return key_file.read_bytes().strip()
        secret = secrets.token_hex(32).encode("utf-8")
        key_file.write_bytes(secret)
        try:
            os.chmod(key_file, 0o600)
        except OSError:
            pass
        return secret

    def _sign_bytes(self, payload: bytes) -> tuple[str, str]:
        digest = hashlib.sha256(payload).hexdigest()
        signature = hmac.new(self._signing_key(), payload, hashlib.sha256).hexdigest()
        return digest, signature

    def save_model(
        self,
        estimator,
        preprocessor,
        model_name: str,
        feature_names: list[str],
        datetime_columns: list[str] | None = None,
        target_classes: list | None = None,
    ) -> dict:
        artifact_id = str(uuid4())
        folder = self.root / artifact_id
        folder.mkdir(parents=True, exist_ok=False)
        model_path = folder / "model_bundle.joblib"
        joblib.dump(
            {
                "estimator": estimator,
                "preprocessor": preprocessor,
                "model_name": model_name,
                "feature_names": feature_names,
                "datetime_columns": datetime_columns or [],
                "target_classes": target_classes or [],
            },
            model_path,
        )
        sha256, hmac_sha256 = self._sign_bytes(model_path.read_bytes())
        manifest = {
            "artifact_id": artifact_id,
            "model_name": model_name,
            "file": "model_bundle.joblib",
            "sha256": sha256,
            "hmac_sha256": hmac_sha256,
            "created_at": datetime.now(timezone.utc).isoformat(),
            "python_sklearn_version": sklearn.__version__,
            "warning": "Only load artifacts signed and generated by this trusted Data Pilot instance; joblib/pickle files can execute code when loaded.",
        }
        (folder / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        return {"artifact_id": artifact_id, "artifact_path": str(model_path.relative_to(self.root)), "manifest": manifest}

    def load_model(self, artifact_id: str) -> dict:
        safe_id = str(UUID(artifact_id))
        folder = (self.root / safe_id).resolve()
        model_path = (folder / "model_bundle.joblib").resolve()
        manifest_path = (folder / "manifest.json").resolve()
        if self.root not in model_path.parents or not model_path.is_file():
            raise FileNotFoundError("Model artifact not found")
        if not manifest_path.is_file():
            raise ValueError("Artifact manifest is missing; refusing to deserialize untrusted model bundle.")
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception as exc:
            raise ValueError("Artifact manifest is unreadable; refusing to deserialize model bundle.") from exc
        expected_hmac = str(manifest.get("hmac_sha256") or "")
        expected_sha256 = str(manifest.get("sha256") or "")
        if not expected_hmac or not expected_sha256:
            raise ValueError("Artifact integrity signature is missing; refusing to deserialize model bundle.")
        actual_sha256, actual_hmac = self._sign_bytes(model_path.read_bytes())
        if not (hmac.compare_digest(actual_sha256, expected_sha256) and hmac.compare_digest(actual_hmac, expected_hmac)):
            raise ValueError("Artifact integrity verification failed; refusing to deserialize untrusted model bundle.")
        return joblib.load(model_path)
